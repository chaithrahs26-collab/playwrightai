let percentage =90;
// >70 --distinction
//>60 -- first class
//>50 -- second class
//>40 -- pass class
//<40 -- Fail

if(percentage>70){
    console.log("Distinction");
}
else if(percentage>60){
    console.log("First Class");
}
else if(percentage>50){
    console.log("Second Class");
}
else if(percentage>40){
    console.log("Pass Class");
}
else{
    console.log("Fail")
}
